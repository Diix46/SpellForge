export function useLocale() {
  // Shared singleton: read from the cookie once, by the server on a rendered
  // page, by the browser otherwise.
  const locale = useState<Locale>('locale', loadLocale)

  function setLocale(l: Locale) {
    locale.value = l
    if (import.meta.client)
      writeCookie(l)
  }

  function toggle() {
    setLocale(locale.value === 'fr' ? 'en' : 'fr')
  }

  /** Translate a key. Falls back to the key itself if missing. */
  function t(key: string): string {
    return messages[locale.value][key] ?? messages.fr[key] ?? key
  }

  // Built from the rarity, so an unknown one shows as itself, not as a key.
  function rarityLabel(rarity?: string): string {
    if (!rarity)
      return ''
    const key = `rarity.${rarity.toLowerCase()}`
    const label = t(key)
    return label === key ? rarity : label
  }

  const isFr = computed(() => locale.value === 'fr')

  // Short locale-aware date (e.g. "22 juin" / "Jun 22") for deck timestamps.
  // Shared by the dashboard and deck tiles so the format stays in one place.
  // In one fixed zone: a server-rendered page must print the same day as the
  // browser that takes it over.
  function formatShortDate(ts: number): string {
    return new Date(ts).toLocaleDateString(locale.value === 'fr' ? 'fr-FR' : 'en-US', { day: '2-digit', month: 'short', timeZone: 'Europe/Paris' })
  }

  return { locale, setLocale, toggle, t, rarityLabel, isFr, formatShortDate }
}
